std::string ReadFile(const fs::path &Path)
{
	std::ifstream File(Path, std::ios::binary);
	return {std::istreambuf_iterator<char>(File), std::istreambuf_iterator<char>()};
}

void WriteFile(const fs::path &Path, const std::string &Text)
{
	std::ofstream File(Path, std::ios::binary | std::ios::trunc);
	File << Text;
}

// The test's own empty folder as the working directory, the old one back afterwards.
class TFolder {
public:
	explicit TFolder(const char *Name)
	{
		Old = fs::current_path();
		Path = fs::temp_directory_path() / Name;
		std::error_code Error;
		fs::remove_all(Path, Error);
		fs::create_directories(Path);
		fs::current_path(Path);
	}
	~TFolder()
	{
		std::error_code Error;
		fs::current_path(Old, Error);
		fs::remove_all(Path, Error);
	}
	TFolder(const TFolder &) = delete;
	TFolder &operator=(const TFolder &) = delete;

	// Tibia.cfg with an old time, so that a write would show.
	void PutTibiaCfg(const std::string &Text) const
	{
		WriteFile(Path / "Tibia.cfg", Text);
		fs::last_write_time(Path / "Tibia.cfg", fs::file_time_type::clock::now() - std::chrono::hours(24));
	}

	fs::path Path;

private:
	fs::path Old;
};

// The options the original's reader takes from TibiaCfg. The open dialogs only on the process's first load: the
// original's duplicate check reads the entries an earlier load left (ReadTibiaCfg, kept), so a dialog read before
// is not added again.
void CheckImported(bool FirstLoad)
{
	bool AutoSend = false;
	CHECK(GetTestServerLogin());
	CHECK(GetFullscreenMode()->Width == 640);
	CHECK(GetFullscreenMode()->Depth == 32);
	CHECK_FALSE(GetWindowsMousepointer());
	CHECK(GetNoStretching());
	CHECK(GetConfineFramerate() == 198);
	CHECK(std::string(GetHotkey(0, &AutoSend)) == "hello patella");
	CHECK_FALSE(AutoSend);
	CHECK(std::string(GetHotkey(1, &AutoSend)) == "exura");
	CHECK(AutoSend);
	CHECK(std::string(GetHotkey(35, &AutoSend)) == "say \"hi\"");
	int x = 0, y = 0, Width = 0, Height = 0;
	bool Maximized = true;
	GetWindowedMode(&x, &y, &Width, &Height, &Maximized);
	CHECK((x == -4 && y == 6 && Width == 800 && Height == 600 && !Maximized));
	CHECK(GetConsoleHeight() == 120);
	CHECK(GetAutomapZoom() == 3);
	CHECK(GetContentWindowSize(4) == 90);
	int Sort[3] = {};
	GetBuddySortmethods(Sort);
	CHECK((Sort[0] == 0 && Sort[1] == 1 && Sort[2] == 2));
	CHECK(GetBuddyHideOffline());
	CHECK(GetInfoMessages());
	CHECK_FALSE(GetPrivateMessages());
	CHECK(GetClassicControl());
	CHECK(GetAttackMode() == 1);
	CHECK(GetChaseMode() == 1);
	CHECK_FALSE(GetSecureMode());
	CHECK(std::string(GetBuddyDescription(123456)) == "\xc4rger = friend");
	CHECK(GetBuddyNotify(123456));
	CHECK(GetBuddyIcon(123456) == 3);
	CHECK(FindBuddy(777) != -1);
	CHECK(IsPermanentBuddyIgnore("Some Friend"));
	CHECK(IsPermanentIgnore("Other One"));
	CHECK(IsKnownHint(4));
	CHECK_FALSE(IsKnownHint(2));
	CHECK_FALSE(GetShowNewHints());
	CHECK_FALSE(GetLevelBar());
	CHECK((GetSkillBar(0) && !GetSkillBar(1) && GetSkillBar(6)));
	CHECK(GetEngine() == 1);
	if (FirstLoad) {
		int *Dialogs = nullptr;
		REQUIRE(GetOpenDialogs(&Dialogs) == 1);
		CHECK(Dialogs[0] == 2);
		delete[] Dialogs;
	}
}

std::optional<patella::settings::TSettingsFile> PatellaIni()
{
	return patella::settings::Load(patella::platform::Platform().FileSystem, patella::settings::FileName);
}

