# Writes tests/golden/commseeds.h (tools/difftest/commseeds.h before issue #30): the decrypted server frames (s2c payloads) of issue #19's
# live recordings, the seeds of communication_tests.cpp's packets (issue #36).
#
# Usage: python -I commseeds.py <recording.jsonl> ... > commseeds.h
# (the recordings are tools/compare_traffic.py's <client>-live.jsonl).
import json, sys

frames = []
for path in sys.argv[1:]:
	for line in open(path, encoding='utf-8'):
		e = json.loads(line)
		if e.get('dir') != 's2c' or 'plain' not in e:
			continue
		frames.append((e['kind'], bytes.fromhex(e['plain']), path.replace('\\', '/').split('/')[-1]))

out = ['// Generated by commseeds.py from issue #19\'s recordings (' + ', '.join(sorted(set(f[2] for f in frames))) + ').',
	'// The decrypted server frames, each the payload of one packet (one or more',
	'// messages); Login is true for the login server\'s.', '',
	'struct TSeedFrame {', '\tbool Login;', '\tint Size;', '\tconst unsigned char *Data;', '};', '']
for i, (kind, data, _) in enumerate(frames):
	rows = []
	for j in range(0, len(data), 24):
		rows.append('\t' + ', '.join('0x%02x' % b for b in data[j:j + 24]) + ',')
	out.append('static const unsigned char SeedData%d[] = {' % i)
	out.extend(rows)
	out.append('};')
out.append('static const TSeedFrame SeedFrames[] = {')
for i, (kind, data, _) in enumerate(frames):
	out.append('\t{%s, %d, SeedData%d},' % ('true' if kind == 'login' else 'false', len(data), i))
out.append('};')
sys.stdout.reconfigure(newline='\n')
sys.stdout.write('\n'.join(out) + '\n')
