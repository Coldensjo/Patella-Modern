"""Build the Linux client's built-in cursor resources (Patella-Modern issue #131).

Usage: python3 -I tools/embed_cursors.py <resource folder> <output.cpp>

Reads cursor_<id>.cur in the folder written by tools/extract_resources.py (or tools/placeholder_resources.py) and writes
a C++ source with the first image of each cursor in the form of an RT_CURSOR resource (the two hot spot words, then the
DIB: platform::DecodeMonochromeCursor's input, src/platform/CursorImage.h) and platform::EmbeddedCursor(id). The source is
generated into the build folder: the bytes of a local Tibia.exe never reach the repository.
"""

import glob
import os
import re
import struct
import sys


def images(path):
	"""The images of a .cur file, [(hot x, hot y, width, height, DIB bytes)], in file order."""
	with open(path, "rb") as f:
		data = f.read()
	reserved, kind, count = struct.unpack_from("<HHH", data, 0)
	if reserved != 0 or kind != 2:
		raise ValueError("%s: not a cursor file" % path)
	found = []
	for index in range(count):
		width, height, colors, reserved, hot_x, hot_y, size, offset = struct.unpack_from("<BBBBHHII", data, 6 + index * 16)
		dib = data[offset:offset + size]
		if len(dib) != size:
			raise ValueError("%s: image %d is cut short" % (path, index))
		found.append((hot_x, hot_y, width or 256, height or 256, dib))
	return found


def main():
	if len(sys.argv) != 3:
		sys.exit("usage: embed_cursors.py <resource folder> <output.cpp>")
	folder, output = sys.argv[1:]
	entries = []
	for path in sorted(glob.glob(os.path.join(folder, "cursor_*.cur"))):
		match = re.fullmatch(r"cursor_(\d+)\.cur", os.path.basename(path))
		if match is None:
			continue
		found = images(path)
		if not found:
			continue
		# LoadCursor picks the system's cursor size (32 x 32); the first image of a size is taken, else the first image.
		chosen = next((image for image in found if image[2] == 32 and image[3] == 32), found[0])
		hot_x, hot_y, _, _, dib = chosen
		entries.append((int(match.group(1)), struct.pack("<HH", hot_x, hot_y) + dib))
	lines = ["// Generated by tools/embed_cursors.py (issue #131): the cursor resources, built in. Not in the repository.",
		'#include "platform/CursorImage.h"', "", "#include <array>", "#include <cstdint>", "#include <span>", "",
		"namespace patella::platform {", "", "namespace {", ""]
	for number, blob in entries:
		bytes_text = ",".join(str(value) for value in blob)
		lines.append("constexpr std::array<std::uint8_t, %d> Cursor%d = {%s};" % (len(blob), number, bytes_text))
	lines += ["", "} // namespace", "", "std::span<const std::uint8_t> EmbeddedCursor(int Id)", "{", "\tswitch (Id) {"]
	for number, _ in entries:
		lines.append("\tcase %d: return Cursor%d;" % (number, number))
	lines += ["\tdefault: return {};", "\t}", "}", "", "} // namespace patella::platform", ""]
	with open(output, "w", encoding="ascii", newline="\n") as f:
		f.write("\n".join(lines))


if __name__ == "__main__":
	main()
